// Copies a rendered variant into the game: node scripts/studio/promote.mjs <name> <variant>
// - resources/sounds/<name>.ogg is written, any old <name>.wav removed
// - the name moves from OWN_SOUNDS to STUDIO_SOUNDS in scripts/sound-map.mjs, so render-sounds.mjs and
//   fetch-assets.mjs never regenerate it
// Run `node scripts/fetch-assets.mjs` afterwards (or `pnpm assets:fetch`) to refresh CREDITS.md.
import { copyFileSync, existsSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { outDir, root } from './lib.mjs'

export const moveToStudio = (source, name) => {
  const inOwn = new RegExp(String.raw`(OWN_SOUNDS = \[[^\]]*?)\s*'${name}',?`)
  let text = source
  if (inOwn.test(text)) text = text.replace(inOwn, '$1')
  const studio = /export const STUDIO_SOUNDS = \[([^\]]*)\]/
  const current = [...(studio.exec(text)?.[1] ?? '').matchAll(/'([^']+)'/g)].map((m) => m[1])
  if (!current.includes(name)) current.push(name)
  const list = `export const STUDIO_SOUNDS = [\n${current.map((n) => `  '${n}',`).join('\n')}\n]`
  return studio.test(text) ? text.replace(studio, list) : `${text.trimEnd()}\n\n// Made in REAPER + Vital by scripts/studio (promote.mjs); never regenerated by render-sounds.mjs.\n${list}\n`
}

export const promote = (name, variant) => {
  const from = join(outDir, `${name}--${variant}.ogg`)
  if (!existsSync(from)) throw new Error(`Nothing rendered at ${from}; run render.mjs first`)
  copyFileSync(from, join(root, 'resources', 'sounds', `${name}.ogg`))
  rmSync(join(root, 'resources', 'sounds', `${name}.wav`), { force: true })
  const map = join(root, 'scripts', 'sound-map.mjs')
  writeFileSync(map, moveToStudio(readFileSync(map, 'utf8'), name))
  console.log(`Promoted ${name} (variant ${variant})`)
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const [name, variant] = process.argv.slice(2)
  if (!name || !variant) throw new Error('Usage: node scripts/studio/promote.mjs <name> <variant>')
  promote(name, variant)
}
